"use strict";

/**
 * Generate (or refresh) each campus's access-point CANDIDATE register.
 *
 *   node tools/campus/generateAccessCandidates.js            report only — writes nothing
 *   node tools/campus/generateAccessCandidates.js --write    write the registers
 *   node tools/campus/generateAccessCandidates.js --campus RNSIT
 *
 * The buildings it proposes for are the dashboard's own list of destination footprints
 * (Frontend `features/tasks/campusLocations.js` `destinationFootprints`), so the two cannot
 * disagree about which buildings lack a point. See `accessCandidates.js` for how a candidate is
 * derived and validated, and `docs/runbooks/campus-access-point-review.md` for how a person
 * verifies one.
 *
 * `--write` writes the same register to the three places the campus data already lives:
 *   <repo>/<campus>-campus-access-candidates.geojson                     the reviewed source
 *   Frontend/src/features/maps/campus/data/<dir>/<same name>              the dashboard's copy
 *   Frontend/src/features/maps/campus/data/<dir>/<module>.js              that copy, as a module
 * A reviewer edits the repository-root file and re-runs `--write`; every entry carrying a
 * `review` is kept, and a `verified` entry without one stops the run.
 *
 * Read-only against every database: it touches none.
 */

const fs = require("fs");
const path = require("path");
const { pathToFileURL } = require("url");

const { generateRegister, STATUS } = require("./accessCandidates");

const REPO_ROOT = path.resolve(__dirname, "..", "..", "..");
const FRONTEND_DATA = path.join(REPO_ROOT, "Frontend", "src", "features", "maps", "campus", "data");

/** The campuses, as the Frontend registry names them. @structural */
const CAMPUSES = Object.freeze([
  Object.freeze({
    campusId: "RNSIT",
    extract: "rnsit-campus-osm.geojson",
    supplemental: "rnsit-campus-supplemental.geojson",
    // The delivery domain `tools/demo/seedV1Demonstration.js` publishes (RD-2026-08-30-01).
    declaration: { regionId: "rnsit-campus", name: "RNSIT Campus", boundaryWay: "way/1120154292", versionDate: "2026-08-30" },
    register: "rnsit-campus-access-candidates.geojson",
    frontendDir: "rnsit",
    module: "rnsitCampusAccessCandidates.js",
    exportName: "RNSIT_CAMPUS_ACCESS_CANDIDATES",
  }),
  Object.freeze({
    campusId: "jssate-bengaluru",
    extract: "jssate-bengaluru-campus-osm.geojson",
    supplemental: null,
    // An EVALUATION declaration: JSSATE has no published operating region.
    declaration: { regionId: "jssate-bengaluru", name: "JSSATE Bengaluru", boundaryWay: "way/106873634", versionDate: "2026-08-30" },
    register: "jssate-bengaluru-campus-access-candidates.geojson",
    frontendDir: "jssate-bengaluru",
    module: "jssateBengaluruCampusAccessCandidates.js",
    exportName: "JSSATE_BENGALURU_CAMPUS_ACCESS_CANDIDATES",
  }),
]);

const read = (file) => ({ file, text: fs.readFileSync(path.join(REPO_ROOT, file), "utf8") });
const serialise = (register) => `${JSON.stringify(register, null, 2)}\n`;

function moduleText(campus, register) {
  return [
    "/**",
    " * ═══════════════════════════════════════════════════════════════════════════",
    ` * ${campus.campusId} — the access-point CANDIDATE register, verbatim`,
    " *",
    ` * The CONTENT of \`data/${campus.frontendDir}/${campus.register}\` re-exported as an ES module,`,
    " * so the same file loads under Vite and under plain `node --test`. Generated by",
    " * Backend/tools/campus/generateAccessCandidates.js; never hand-edit. Review the repository-root",
    " * copy and regenerate (docs/runbooks/campus-access-point-review.md).",
    " *",
    " * Every entry is a SUGGESTION until its status is `verified` with a review. Only those",
    " * become campus features (`access/accessPointImport.js`); nothing else here is offered.",
    " * ═══════════════════════════════════════════════════════════════════════════",
    " */",
    "",
    "/** The access-point register, verbatim. Generated — treat as read-only. */",
    `export const ${campus.exportName} = ${JSON.stringify(register, null, 2)};`,
    "",
  ].join("\n");
}

function summarise(campus, register) {
  const counts = {};
  for (const feature of register.features) counts[feature.properties.status] = (counts[feature.properties.status] || 0) + 1;
  const lines = [`\n${campus.campusId} — ${register.features.length} candidate(s) ${JSON.stringify(counts)}`];
  for (const building of register.buildings) {
    lines.push(
      `  ${building.buildingSourceId.padEnd(18)} ${String(building.name).padEnd(30)} ` +
        `${building.candidates.length} candidate(s), ${building.reliableCandidates} not rejected` +
        (building.reliableCandidates === 0 ? "  ← NO RELIABLE CANDIDATE" : ""),
    );
  }
  for (const feature of register.features) {
    const p = feature.properties;
    const [lon, lat] = feature.geometry.coordinates;
    lines.push(
      `    ${p.status.padEnd(12)} ${p.buildingName.padEnd(30)} ${lat.toFixed(6)}, ${lon.toFixed(6)}  ` +
        `gap ${p.measurements ? p.measurements.frontageGapM : "?"} m  ` +
        [...(p.flags || []), ...(p.rejections || [])].join(", "),
    );
  }
  const verified = register.features.filter((feature) => feature.properties.status === STATUS.VERIFIED).length;
  lines.push(`  verified (offered as task locations): ${verified}`);
  return lines.join("\n");
}

async function main(argv) {
  const write = argv.includes("--write");
  const only = argv.includes("--campus") ? argv[argv.indexOf("--campus") + 1] : null;
  const locations = await import(pathToFileURL(path.join(REPO_ROOT, "Frontend", "src", "features", "tasks", "campusLocations.js")).href);

  for (const campus of CAMPUSES) {
    if (only && campus.campusId !== only) continue;
    const registerPath = path.join(REPO_ROOT, campus.register);
    const existing = fs.existsSync(registerPath) ? JSON.parse(fs.readFileSync(registerPath, "utf8")) : null;
    const register = await generateRegister({
      campusId: campus.campusId,
      extract: read(campus.extract),
      supplemental: campus.supplemental ? read(campus.supplemental) : null,
      declarationSettings: campus.declaration,
      targets: locations.destinationFootprints(campus.campusId).map((row) => ({
        sourceId: row.sourceId,
        featureId: row.featureId,
        name: row.name,
        operationalRole: row.operationalRole,
        related: row.related,
      })),
      existing,
    });
    console.log(summarise(campus, register));

    if (write) {
      const text = serialise(register);
      fs.writeFileSync(registerPath, text);
      fs.writeFileSync(path.join(FRONTEND_DATA, campus.frontendDir, campus.register), text);
      fs.writeFileSync(path.join(FRONTEND_DATA, campus.frontendDir, campus.module), moduleText(campus, register));
      console.log(`  wrote ${campus.register} (+ Frontend copy and ${campus.module})`);
    }
  }
  if (!write) console.log("\nReport only. Re-run with --write to update the registers.");
}

if (require.main === module) {
  main(process.argv.slice(2)).catch((error) => {
    console.error(error && error.stack ? error.stack : error);
    process.exit(1);
  });
}

module.exports = { CAMPUSES, moduleText, serialise };
