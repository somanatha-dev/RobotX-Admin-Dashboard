#!/usr/bin/env node
"use strict";

/**
 * Write the RNSIT four-zone PROPOSAL (layout G4, validated stage) as a static, display-only
 * snapshot for the dashboard's off-by-default "proposal preview".
 *
 *   node tools/demo/dtaro/exportZoneProposalPreview.js            # writes the frontend module
 *   node tools/demo/dtaro/exportZoneProposalPreview.js --check    # exit 1 if the module is stale
 *
 * The proposal (`tools/campus/rnsitZoneLayoutG4.js`, `RNSIT_ZONE_LAYOUT_G4_PROPOSAL.md`) is
 * validated offline but NOT approved and NOT published. This snapshot changes neither fact:
 *   · it is read by the dashboard only, behind a toggle labelled as a proposal, and never by
 *     alert routing, membership or any backend path;
 *   · it carries the proposal's own status, `approved: false`, `published: false`, and the
 *     digest of its cell assignment, so a changed proposal shows up as a stale snapshot;
 *   · it refuses to write a proposal that claims approval or fails its own validation.
 *
 * (Until 2026-10-23 this exported the earlier L4 candidate, with 14 tied cells and no zone.)
 */

const fs = require("fs");
const path = require("path");
const h3 = require("h3-js");

const BACKEND_ROOT = path.resolve(__dirname, "..", "..", "..");
const OUT = path.resolve(BACKEND_ROOT, "..", "Frontend", "src", "features", "maps", "dtaro", "rnsitZoneProposalPreview.js");
const g4 = require(path.join(BACKEND_ROOT, "tools/campus/rnsitZoneLayoutG4"));

/** Six decimals (~0.1 m): the snapshot is a picture, and shorter numbers keep it reviewable. */
const round6 = (ring) => ring.map(([lon, lat]) => [Math.round(lon * 1e6) / 1e6, Math.round(lat * 1e6) / 1e6]);
const multi = (cellIds) => h3.cellsToMultiPolygon([...cellIds].sort(), true).map((polygon) => polygon.map(round6));

function build() {
  const context = g4.loadContext();
  const proposal = g4.buildProposal({ context });
  const validation = g4.validateLayout(proposal, context);
  const byZone = new Map(proposal.zones.map((zone) => [zone.id, []]));
  for (const row of proposal.cells) if (row.zoneId) byZone.get(row.zoneId).push(row.cellId);

  return {
    kind: "PROPOSAL_PREVIEW",
    layout: proposal.layout,
    stage: proposal.stage,
    validated: validation.passed,
    approved: proposal.approved === true,
    published: proposal.published === true,
    status: proposal.status,
    campusCode: "RNSIT",
    regionKey: "rnsit",
    source: "Backend/tools/campus/rnsitZoneLayoutG4.js (docs/audits/dtaro-zone-coordination/RNSIT_ZONE_LAYOUT_G4_PROPOSAL.md)",
    assignmentDigest: g4.assignmentDigest(proposal),
    zones: proposal.zones.map((zone) => ({
      zoneId: zone.id,
      name: zone.name.split(" — ")[0].replace(/^RNSIT /, ""),
      contents: zone.name.split(" — ")[1] || null,
      cellCount: byZone.get(zone.id).length,
      geometry: { type: "MultiPolygon", coordinates: multi(byZone.get(zone.id)) },
    })),
    unresolved: { cellCount: proposal.unresolved.length, geometry: { type: "MultiPolygon", coordinates: multi(proposal.unresolved) } },
    // Every assigned cell, for the thin cell grid the preview draws inside each zone.
    cells: proposal.cells.map((row) => ({
      cellId: row.cellId,
      zoneId: row.zoneId,
      decided: Boolean(row.decision),
      ring: round6(h3.cellToBoundary(row.cellId, true)),
    })),
  };
}

function render(preview) {
  return (
    "// GENERATED by Backend/tools/demo/dtaro/exportZoneProposalPreview.js — do not edit by hand.\n" +
    "//\n" +
    "// The G4 four-zone PROPOSAL, validated offline, NOT approved and NOT published (`approved: false`,\n" +
    "// `published: false`). Display only: the dashboard shows it behind an off-by-default toggle\n" +
    "// labelled as a proposal. Alert routing and zone membership never read it.\n" +
    `export const RNSIT_ZONE_PROPOSAL_PREVIEW = Object.freeze(${JSON.stringify(preview)});\n`
  );
}

const preview = build();
if (preview.approved || preview.published) {
  // An approved map is published through the Config Service and reaches the dashboard through
  // `/api/dtaro/zones`, never through this snapshot.
  process.stderr.write("The proposal reports approved or published — publish it instead of previewing it. Nothing written.\n");
  process.exit(1);
}
if (!preview.validated) {
  process.stderr.write("The G4 proposal fails its own validation (rnsitZoneLayoutG4.validateLayout). Nothing written.\n");
  process.exit(1);
}
const text = render(preview);
const normalise = (s) => s.replace(/\r\n/g, "\n");
if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (normalise(current) !== normalise(text)) {
    process.stderr.write(`STALE: ${OUT} does not match the current proposal (digest ${preview.assignmentDigest}).\n`);
    process.exit(1);
  }
  process.stdout.write(`up to date (layout ${preview.layout}, digest ${preview.assignmentDigest})\n`);
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, text);
  process.stdout.write(
    `wrote ${OUT}\n  layout ${preview.layout} (${preview.stage}, validated ${preview.validated}): ` +
      `${preview.zones.map((z) => `${z.zoneId}: ${z.cellCount}`).join(", ")}, unresolved: ${preview.unresolved.cellCount}\n`,
  );
}
